import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';

test('explicit writes, save-and-quit, and Vim directory navigation', async () => {
  const dom = new JSDOM('<div id="app"></div>', {url:'http://localhost', pretendToBeVisual:true});
  for (const name of ['window','Window','document','MutationObserver','HTMLElement','Node','KeyboardEvent','InputEvent','Event','localStorage']) globalThis[name]=dom.window[name];
  Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
  globalThis.requestAnimationFrame=dom.window.requestAnimationFrame.bind(dom.window);
  globalThis.cancelAnimationFrame=dom.window.cancelAnimationFrame.bind(dom.window);
  dom.window.Range.prototype.getClientRects=()=>[];
  dom.window.Range.prototype.getBoundingClientRect=()=>({left:0,right:0,top:0,bottom:0,width:0,height:0});
  const writes=[];
  let failWrite=false, finishWrite;
  globalThis.fetch=async (url,options) => {
    if(options?.method==='PUT'){
      writes.push(JSON.parse(options.body));
      if(failWrite)return {ok:false,json:async()=>({error:'Disk full'})};
      if(finishWrite)await new Promise(resolve=>{finishWrite=resolve;});
    }
    return {ok:true,json:async()=> url==='/api/notes'?[{name:'One.md',content:'original',updated:'2026-10-14'},{name:'Two.md',content:'second',updated:'2026-10-14'}]:url==='/api/config'?{storage:'/notes'}:url==='/api/vimrc'?{content:'',path:'/notes/.vimrc'}:{}};
  };
  let source=await readFile(new URL('../src/main.js',import.meta.url),'utf8');
  source=source.replace("import './style.css';",'').replace(/from '([^']+)'/g,(_,specifier)=>`from '${specifier.startsWith('.')?new URL('../src/'+specifier,import.meta.url).href:import.meta.resolve(specifier)}'`);
  await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  await new Promise(resolve=>setTimeout(resolve,20));
  const {EditorView}=await import('codemirror');
  const {Vim,getCM}=await import('@replit/codemirror-vim');
  let view=EditorView.findFromDOM(document.querySelector('.cm-editor'));
  view.dispatch({changes:{from:0,to:view.state.doc.length,insert:'draft'}});
  await new Promise(resolve=>setTimeout(resolve,700));
  window.dispatchEvent(new KeyboardEvent('keydown',{key:'s',metaKey:true,bubbles:true,cancelable:true}));
  assert.equal(writes.length,0);
  Vim.handleEx(getCM(view),'q');
  assert.equal(document.querySelector('#content').hidden,true);
  assert.equal(document.querySelectorAll('#directory [data-name]').length,2);
  document.querySelector('#directory [data-name="One.md"]').click();
  view=EditorView.findFromDOM(document.querySelector('.cm-editor'));
  assert.equal(view.state.doc.toString(),'draft');
  document.querySelector('#notes [data-name="Two.md"]').click();
  assert.equal(writes.length,0);
  document.querySelector('#notes [data-name="One.md"]').click();
  view=EditorView.findFromDOM(document.querySelector('.cm-editor'));
  Vim.handleEx(getCM(view),'w');
  await new Promise(resolve=>setTimeout(resolve,20));
  assert.deepEqual(writes,[{content:'draft'}]);
  view.dispatch({changes:{from:0,to:view.state.doc.length,insert:'saved on quit'}});
  finishWrite=true;
  Vim.handleEx(getCM(view),'wq');
  await new Promise(resolve=>setTimeout(resolve,20));
  assert.equal(document.querySelector('#content').hidden,false, 'wait for the write before quitting');
  finishWrite();
  finishWrite=null;
  await new Promise(resolve=>setTimeout(resolve,20));
  assert.equal(document.querySelector('#content').hidden,true);
  assert.equal(writes.at(-1).content,'saved on quit');
  const key=value=>document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:value,bubbles:true,cancelable:true}));
  assert.equal(document.activeElement.dataset.name,'One.md');
  key('j'); assert.equal(document.activeElement.dataset.name,'Two.md');
  key('k'); assert.equal(document.activeElement.dataset.name,'One.md');
  key('G'); assert.equal(document.activeElement.dataset.name,'Two.md');
  key('g'); key('g'); assert.equal(document.activeElement.dataset.name,'One.md');
  key('2'); key('j'); assert.equal(document.activeElement.dataset.name,'Two.md');
  key('Enter');
  view=EditorView.findFromDOM(document.querySelector('.cm-editor'));
  assert.equal(view.state.doc.toString(),'second');
  assert.equal(document.activeElement,view.contentDOM);
  view.dispatch({changes:{from:0,to:view.state.doc.length,insert:'failed write'}});
  failWrite=true;
  Vim.handleEx(getCM(view),'wq');
  await new Promise(resolve=>setTimeout(resolve,20));
  assert.equal(document.querySelector('#content').hidden,false);
  assert.match(document.querySelector('#saved').textContent,/Save failed/);
  failWrite=false;
  Vim.handleEx(getCM(view),'q');
  key('l');
  view=EditorView.findFromDOM(document.querySelector('.cm-editor'));
  assert.equal(view.state.doc.toString(),'failed write');
  const sidebar=document.querySelector('#notes [data-name="One.md"]');
  sidebar.focus(); key('j');
  assert.equal(document.activeElement.dataset.name,'Two.md');
  view.destroy();
  dom.window.close();
});
